// Spreadsheet template download + import. Uses global `XLSX` (SheetJS, loaded via CDN).
//
// Layout (phone-friendly):
//   • Each CATEGORY is its own tab. The tab name is the category on the board.
//   • Start a tab name with "DJ " to put it in the Double Jeopardy round.
//   • A tab named "Final Jeopardy" holds the final clue (Category | Question | Answer).
//   • Category tabs have:  Points | Question | Answer | Other choices | Daily Double
//       - Points blank → auto-numbers ($100–$500, or $200–$1000 in Double Jeopardy)
//       - Other choices → wrong options separated by ";" makes it multiple choice
//
// The full sample template is generated by tools/make_template.py.

export const COLUMNS = ["Points", "Question", "Answer", "Other choices", "Daily Double"];

export async function downloadTemplate() {
  try {
    const res = await fetch("./christmas-jeopardy-template.xlsx", { cache: "no-store" });
    if (res.ok) {
      const url = URL.createObjectURL(await res.blob());
      const a = document.createElement("a");
      a.href = url;
      a.download = "christmas-jeopardy-template.xlsx";
      document.body.appendChild(a);
      a.click();
      a.remove();
      setTimeout(() => URL.revokeObjectURL(url), 2000);
      return;
    }
  } catch { /* fall back to a minimal generated template */ }
  const wb = XLSX.utils.book_new();
  const add = (name, rows) => XLSX.utils.book_append_sheet(wb, XLSX.utils.aoa_to_sheet(rows), name);
  add("Read me first", [["Each tab is a category. Start a tab name with 'DJ ' for Double Jeopardy. See the README for details."]]);
  add("My Category", [COLUMNS, [100, "Your clue here", "The answer", "", ""], [200, "A multiple-choice clue", "Right answer", "Wrong 1; Wrong 2; Wrong 3", ""]]);
  add("DJ My Category", [COLUMNS, [200, "A Double Jeopardy clue", "The answer", "", ""]]);
  add("Final Jeopardy", [["Category", "Question", "Answer"], ["Final category", "The final clue", "The answer"]]);
  XLSX.writeFile(wb, "christmas-jeopardy-template.xlsx");
}

const truthy = (v) => ["yes", "y", "true", "1", "x", "✓", "dd"].includes(String(v || "").trim().toLowerCase());
const letterToIndex = (s) => (s == null ? -1 : "ABCDEF".indexOf(String(s).trim().toUpperCase()));
const isSkippableTab = (name) => /read ?me|instruction|notes|^help$|^info$|^how to/i.test(name);
const FINAL_RE = /^final(\s*jeopardy!?)?$/i;
const DJ_RE = /^(dj|double(\s*jeopardy!?)?)\s*[:\-–—]?\s+/i;

function splitChoices(s) {
  const raw = String(s || "").trim();
  if (!raw) return [];
  const parts = /[\n;|]/.test(raw) ? raw.split(/[\n;|]+/) : raw.split(",");
  const seen = new Set();
  const out = [];
  for (const p of parts) {
    const v = p.trim();
    if (v && !seen.has(v.toLowerCase())) { seen.add(v.toLowerCase()); out.push(v); }
  }
  return out;
}
function shuffle(arr) {
  const a = arr.slice();
  for (let i = a.length - 1; i > 0; i--) {
    const j = Math.floor(Math.random() * (i + 1));
    [a[i], a[j]] = [a[j], a[i]];
  }
  return a;
}

// Returns { rows, summary, error }
export function parseWorkbook(arrayBuffer) {
  const wb = XLSX.read(arrayBuffer, { type: "array" });
  if (!wb.SheetNames.length) return { error: "The spreadsheet has no tabs." };

  const rows = [];
  const cats = { 1: [], 2: [] };
  let order = 0;
  let finalRow = null;

  for (const sheetName of wb.SheetNames) {
    const tab = String(sheetName).trim();
    if (!tab || isSkippableTab(tab)) continue;
    const aoa = XLSX.utils.sheet_to_json(wb.Sheets[sheetName], { header: 1, blankrows: false, defval: "" });
    const headerIdx = aoa.findIndex((r) => r.some((c) => ["question", "clue"].includes(String(c).trim().toLowerCase())));
    if (headerIdx < 0) continue;

    const header = aoa[headerIdx].map((c) => String(c).trim().toLowerCase());
    const col = (names) => { for (const n of names) { const i = header.indexOf(n); if (i >= 0) return i; } return -1; };
    const idx = {
      category: col(["category"]),
      points: col(["points", "value", "$"]),
      question: col(["question", "clue"]),
      answer: col(["answer", "correct answer", "response"]),
      other: col(["other choices", "other options", "wrong options", "wrong answers", "choices", "options"]),
      dd: col(["daily double", "dailydouble", "daily-double", "dd"]),
      type: col(["type"]),
      a: col(["choice a"]), b: col(["choice b"]), c: col(["choice c"]), d: col(["choice d"]),
      correct: col(["correct"]),
      final: col(["final jeopardy"]),
    };
    const isFinalTab = FINAL_RE.test(tab);
    const round = DJ_RE.test(tab) ? 2 : 1;
    const tabCategory = tab.replace(DJ_RE, "").trim() || tab;
    const step = round === 2 ? 200 : 100;

    let auto = 0;
    for (let i = headerIdx + 1; i < aoa.length; i++) {
      const r = aoa[i];
      const get = (k) => (idx[k] >= 0 ? r[idx[k]] : "");
      const question = String(get("question") || "").trim();
      if (!question) continue;
      const answer = String(get("answer") || "").trim();
      const legacyFinal = idx.final >= 0 && truthy(get("final"));

      if (isFinalTab || legacyFinal) {
        if (!finalRow) {
          const cat = String(get("category") || "").trim();
          finalRow = {
            category: cat && !FINAL_RE.test(cat) ? cat : "Final Jeopardy",
            points: 0, question, answer, type: "spoken", choices: [], correctIndex: -1,
            dailyDouble: false, isFinal: true, round: 0, order: order++, used: false,
          };
        }
        continue;
      }
      auto += step;

      // Category: the tab name, unless an old one-sheet template has a Category column.
      const legacyCat = String(get("category") || "").trim();
      const category = idx.category >= 0 && legacyCat ? legacyCat.replace(DJ_RE, "").trim() : tabCategory;

      let type = "spoken";
      let choices = [];
      let correctIndex = -1;
      const typeExplicit = String(get("type") || "").trim().toLowerCase();
      const legacy = [get("a"), get("b"), get("c"), get("d")].map((x) => String(x || "").trim());
      const other = splitChoices(get("other"));
      if (typeExplicit !== "spoken") {
        if (legacy.some((x) => x)) {
          choices = legacy.filter((x) => x);
          correctIndex = letterToIndex(get("correct"));
          if (correctIndex < 0 && answer) correctIndex = Math.max(0, choices.findIndex((c) => c.toLowerCase() === answer.toLowerCase()));
          type = "mcq";
        } else if (other.length && answer) {
          const all = shuffle([answer, ...other.filter((o) => o.toLowerCase() !== answer.toLowerCase())]).slice(0, 6);
          choices = all;
          correctIndex = all.findIndex((c) => c.toLowerCase() === answer.toLowerCase());
          type = "mcq";
        }
      }
      const row = {
        category, points: Number(get("points")) || auto, question, answer, type,
        choices: type === "mcq" ? choices : [], correctIndex: type === "mcq" ? correctIndex : -1,
        dailyDouble: truthy(get("dd")), isFinal: false, round, order: order++, used: false,
      };
      rows.push(row);
      if (!cats[round].includes(category)) cats[round].push(category);
    }
  }
  if (finalRow) rows.push(finalRow);
  const r1 = rows.filter((r) => !r.isFinal && r.round === 1).length;
  const r2 = rows.filter((r) => !r.isFinal && r.round === 2).length;
  if (!r1 && !r2) return { error: "No clues found. Each category should be its own tab with a 'Question' column." };
  if (!r1 && r2) return { error: "Only Double Jeopardy tabs were found — add at least one regular category tab (without “DJ ”)." };
  const parts = [`${r1} clues in ${cats[1].length} categories`];
  if (r2) parts.push(`${r2} Double Jeopardy clues in ${cats[2].length} categories`);
  parts.push(finalRow ? "Final Jeopardy ✓" : "no Final Jeopardy tab");
  return { rows, summary: "Imported " + parts.join(" · ") + "." };
}
