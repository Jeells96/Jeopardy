export function punText(arr, idx, name) {
  const list = arr && arr.length ? arr : [""];
  const i = (typeof idx === "number" && idx >= 0 && idx < list.length) ? idx : 0;
  return list[i].replace(/\{name\}/g, name || "they");
}
export function pickPunIndex(len, prev) {
  if (len <= 1) return 0;
  let i = Math.floor(Math.random() * len);
  if (i === prev) i = (i + 1) % len; // avoid immediate repeat
  return i;
}
